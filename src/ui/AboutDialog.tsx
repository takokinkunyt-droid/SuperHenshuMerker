import { Modal } from './common';
import { VISUAL_FX } from '../fx/visual';
import { AUDIO_FX } from '../fx/audio';

const SHORTCUTS: [string, string][] = [
  ['Space', '再生／停止'],
  ['← / →', '1フレーム移動（Shiftで1秒）'],
  ['Home', '先頭へ'],
  ['S', '再生位置で分割'],
  ['Delete / Backspace', '選択アイテムを削除'],
  ['Ctrl+D', '選択アイテムを複製'],
  ['Ctrl+C / Ctrl+V', 'コピー／再生位置に貼り付け'],
  ['Ctrl+Z / Ctrl+Shift+Z（Ctrl+Y）', '元に戻す／やり直す'],
  ['Ctrl+ホイール', 'タイムラインの拡大・縮小（マウスの位置が中心）'],
  ['Ctrl+A', 'すべて選択'],
  ['End', '最後へ移動'],
];

export function AboutDialog({ onClose }: { onClose: () => void }) {
  return (
    <Modal title="スーパー編集メーカーの使い方" onClose={onClose} wide>
      <p>
        ブラウザだけで動画を編集できるツールです。インストール不要で、スマホでも使えます。編集・保存・書き出しはすべてブラウザの中で行われ、素材が外部に送信されることはありません。
      </p>
      <h4>基本の流れ</h4>
      <ol>
        <li>プロジェクト設定（何も選んでいないときの右側／スマホでは下）で、画面の比率を選びます（16:9・9:16・1:1）。</li>
        <li>「🎞 動画・画像」で映像を、「🎵 音楽」でBGMや効果音を、「T テキスト」で文字を追加します。</li>
        <li>タイムラインでアイテムを動かしたり、端をつかんで長さを変えたり、「✂ 分割」で切ったりします。</li>
        <li>「書き出し」から動画（MP4）として保存します。</li>
      </ol>
      <h4>プレビューで直接操作する</h4>
      <ul>
        <li>プレビュー上のテキスト・画像・動画をクリック／タップすると選択され、青い枠が出ます。</li>
        <li>ドラッグで移動、四隅の白いつまみで拡大縮小、上の丸いつまみ（⟳）で回転します（Shiftを押すと15°ずつ）。</li>
        <li>スマホでは2本指でつまむと、拡大縮小と回転を同時にできます。</li>
        <li>テキストはダブルクリック／ダブルタップか「✏ 編集」で、プレビューの文字をそのまま書き換えられます（打った文字がすぐ本番の見た目で表示されます）。入力中でも文字をドラッグすれば移動でき、外を触るか「完了」で終了、Escキーで取り消し。文字を全部消すとテキストごと削除されます。</li>
      </ul>
      <h4>位置をぴったり合わせる</h4>
      <ul>
        <li>プレビュー上でテキスト・画像・動画をドラッグすると、画面の中央・端・余白や、ほかのアイテムの端・中央に吸着します（ピンクの線が目印）。Altキーを押している間は吸着しません。</li>
        <li>設定の「そろえる」ボタンで、左・中央・右／上・中央・下にワンタッチで合わせられます。</li>
      </ul>
      <h4>読み上げ（合成音声）</h4>
      <ul>
        <li>「🗣 読み上げ」から、VOICEVOX の声で文章を読み上げた音声を作れます。1行ごとに1つの音声になり、再生位置から順に並びます。同じ文章の字幕も一緒に追加できます。</li>
        <li>作った音声を選ぶと、読み上げる文字や声を変えて作り直せます（一緒に作った字幕も変わります）。</li>
        <li>パソコンで VOICEVOX を起動しておく必要があります。使った声のクレジット表記は書き出し画面に表示されます。</li>
        <li>スマホで使うときは、VOICEVOX を持っている人から「共有リンク」を送ってもらって開いてください。自動で設定されます。</li>
      </ul>
      <h4>共同作業（みんなで編集）</h4>
      <ul>
        <li>「👥 共同作業」→「共同作業を始める」で招待リンクができます。リンクを開いた人と、同じプロジェクトを一緒に編集できます。</li>
        <li>変更はすぐ相手の画面に反映されます。動画・画像・音楽も自動で届きます。相手が選んでいるアイテムには名前が出ます。</li>
        <li>同じアイテムを同時に変えたときは、あとから変えた方が残ります。「戻す」で戻るのは自分の変更だけです。</li>
        <li>共有サーバー（読み上げの共有と同じもの）を動かしている間だけ使えます。</li>
      </ul>
      <h4>エフェクト</h4>
      <ul>
        <li>アイテムを選び、設定の「映像エフェクト」「音声エフェクト」の「＋ 追加」から選びます。名前で検索でき、いくつでも重ねられます（上から順にかかります）。</li>
        <li>映像：登場退場・アニメーション・描画・加工・装飾・合成・配置・カメラの{VISUAL_FX.length}種類。音声：エコー・音程・フィルターなど{AUDIO_FX.length}種類。</li>
        <li>映像エフェクトの数値は「→ 変化」を押すと、アイテムの始めから終わりにかけて値を変えられます（だんだん拡大する、移動する、など）。</li>
        <li>チェックを外すと一時的にオフ、↑↓で順番の入れ替え、✕で削除です。エフェクトがかかったアイテムには ✨ が付きます。</li>
        <li>一部分だけにかけたいとき（ピー音など）は、「✂ 分割」でその部分を切り出してからかけます。</li>
      </ul>
      <h4>タイムラインとレイヤー</h4>
      <ul>
        <li>何も無いところをドラッグすると範囲選択、Ctrl（Shift）を押しながらクリックすると選択に足せます。選んだアイテムはまとめて移動・複製・コピー・削除できます。</li>
        <li>アイテムを置きたい場所がふさがっているときは、一番近い空いているレイヤーに入ります。ほかのアイテムの端や赤い線に近づくと、ぴったり合います（黄色い点線。Altで解除）。</li>
        <li>レイヤーの左の 👁 で表示／非表示（音も消えます）、🔓 でロック（動かせなくなります）。番号を押す（または右クリック）と、名前をつける・レイヤーを入れる・入れ替える・削除するメニューが出ます。</li>
        <li>アイテムや何も無いところを右クリックすると、分割・複製・コピー・貼り付けなどのメニューが出ます。</li>
        <li>何時間もある長い動画・音楽も読み込めます（音声は必要な部分だけを少しずつ読みます）。</li>
      </ul>
      <h4>再生位置（赤い線）の動かし方</h4>
      <ul>
        <li>タイムラインの上の目盛りや、赤い線の上のつまみをドラッグする</li>
        <li>何も無いところをクリック／タップするとその位置へ移動</li>
        <li>スマホでは、何も無いところを長押ししたまま指を動かすと、赤い線がついてきます</li>
      </ul>
      <h4>スマホでの操作</h4>
      <ul>
        <li>画面下のタブで「タイムライン」「素材」「編集（設定）」を切り替えます。素材と編集はプレビューを見ながら操作できます。</li>
        <li>タイムラインのアイテムは、タップで選んでからドラッグすると移動できます。選んでいないアイテムは、長押ししてから動かすと移動、すぐ動かすとスクロールです。</li>
        <li>選んだアイテムの両端の白いつまみで長さを変えられます。</li>
        <li>書き出しが終わったら「共有・写真に保存」から写真アプリなどに保存できます。</li>
      </ul>
      <h4>ショートカット（パソコン）</h4>
      <table className="shortcut-table">
        <tbody>
          {SHORTCUTS.map(([k, v]) => (
            <tr key={k}>
              <td>
                <kbd>{k}</kbd>
              </td>
              <td>{v}</td>
            </tr>
          ))}
        </tbody>
      </table>
      <p className="muted small">使った音楽・映像の利用条件（著作権・クレジット表記など）は、それぞれの提供元の規約に従ってください。</p>
      <h4>使用しているソフトウェア</h4>
      <p className="muted small">React、Zustand、Immer、fflate（MIT）、Mediabunny・@mediabunny/aac-encoder（MPL-2.0）</p>
      <p className="muted small">
        フォント（SIL Open Font License 1.1）：Noto Sans JP、Noto Serif JP、M PLUS Rounded 1c、Zen Maru Gothic、Kosugi Maru、Dela Gothic One、RocknRoll One、Reggae One、Mochiy Pop One、Hachi Maru Pop、Yusei Magic、Zen Kurenaido、DotGothic16
      </p>
    </Modal>
  );
}
